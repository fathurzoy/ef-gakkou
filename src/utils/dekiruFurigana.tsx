interface SmartFuriganaProps {
  segments?: TextSegment[];
  text?: string;
  showFurigana?: boolean;
  className?: string;
  fontSize?: string;
}

/**
 * Smart Furigana component that supports:
 * - Direct SegmentContent or raw text
 * - Automatic dictionary enrichment for missing readings
 * - Global Furigana toggle (show/hide)
 */
export const SmartFurigana: React.FC<SmartFuriganaProps> = ({
  segments,
  text,
  showFurigana = true,
  className = "",
  fontSize,
}) => {
  let finalSegments: TextSegment[] = [];

  if (segments && segments.length > 0) {
    finalSegments = enrichSegmentsWithFurigana(segments);
  } else if (text) {
    finalSegments = annotateTextWithFurigana(text);
  }

  if (finalSegments.length === 0) return null;

  return (
    <span className={`smart-furigana ${className}`} style={fontSize ? { fontSize } : undefined}>
      {finalSegments.map((seg, idx) => {
        if (seg.reading && showFurigana) {
          return (
            <ruby key={idx} style={{ margin: "0 1px" }}>
              {seg.text}
              <rt
                style={{
                  fontFamily: "var(--font-jp)",
                  fontSize: "0.58em",
                  lineHeight: 1,
                  textAlign: "center",
                  color: "#4f46e5",
                  fontWeight: 600,
                  userSelect: "none",
                }}
              >
                {seg.reading}
              </rt>
            </ruby>
          );
        }

        // Multiline split if newline
        if (seg.text.includes("\n")) {
          const lines = seg.text.split("\n");
          return (
            <React.Fragment key={idx}>
              {lines.map((line, lineIdx) => (
                <React.Fragment key={lineIdx}>
                  {lineIdx > 0 && <br />}
                  {line}
                </React.Fragment>
              ))}
            </React.Fragment>
          );
        }

        return <span key={idx}>{seg.text}</span>;
      })}
    </span>
  );
};

interface SmartRomajiProps {
  text?: string;
  segments?: TextSegment[];
  className?: string;
  prefix?: string;
  style?: React.CSSProperties;
}

/**
 * Smart Romaji component that outputs clean Latin Hepburn romanization.
 */
export const SmartRomaji: React.FC<SmartRomajiProps> = ({
  text,
  segments,
  className = "",
  prefix = "🔤 ",
  style,
}) => {
  const romaji = toRomaji(segments && segments.length > 0 ? segments : text);
  if (!romaji) return null;

  return (
    <span
      className={`smart-romaji ${className}`}
      style={{
        display: "inline-flex",
        alignItems: "center",
        gap: "0.25rem",
        fontSize: "0.84rem",
        fontWeight: 500,
        color: "#4338ca",
        letterSpacing: "0.01em",
        fontFamily: "ui-sans-serif, system-ui, -apple-system, BlinkMacSystemFont, Roboto, sans-serif",
        ...style,
      }}
      title="Cara Baca Huruf Latin (Romaji)"
    >
      {prefix && <span style={{ opacity: 0.85, fontSize: "0.8rem", userSelect: "none" }}>{prefix}</span>}
      <span>{romaji}</span>
    </span>
  );
};
