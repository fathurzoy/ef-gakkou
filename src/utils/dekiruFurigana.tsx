const KANA_MAP: Record<string, string> = { ...HIRAGANA_MAP, ...KATAKANA_MAP };

export function kanaToRomaji(kanaStr: string): string {
  if (!kanaStr) return "";
  let res = "";
  let i = 0;

  while (i < kanaStr.length) {
    const two = kanaStr.slice(i, i + 2);
    if (KANA_MAP[two]) {
      res += KANA_MAP[two];
      i += 2;
      continue;
    }

    const c = kanaStr[i];
    if (c === "っ" || c === "ッ") {
      const nextTwo = kanaStr.slice(i + 1, i + 3);
      const nextOne = kanaStr[i + 1];
      const nextRom = KANA_MAP[nextTwo] || KANA_MAP[nextOne] || "";
      if (nextRom) {
        res += nextRom.startsWith("ch") ? "t" : nextRom[0];
      }
      i++;
      continue;
    }

    if (c === "ー") {
      const lastChar = res[res.length - 1];
      if (/[aeiou]/.test(lastChar)) {
        res += lastChar;
      }
      i++;
      continue;
    }

    if (KANA_MAP[c]) {
      if ((c === "ん" || c === "ン") && i + 1 < kanaStr.length) {
        const nextTwo = kanaStr.slice(i + 1, i + 3);
        const nextOne = kanaStr[i + 1];
        const nextRom = KANA_MAP[nextTwo] || KANA_MAP[nextOne] || "";
        if (nextRom && /^[aeiouy]/.test(nextRom)) {
          res += "n'";
          i++;
          continue;
        }
      }
      res += KANA_MAP[c];
    } else {
      res += c;
    }
    i++;
  }

  return res;
}

function tokenizeKanaText(text: string): string {
  let s = text;
  s = s.replace(/^は(?=[\s\u3040-\u30ff])/g, "wa ");
  s = s.replace(/([^\s])は(?=[\s\u3040-\u30ff])/g, "$1 wa ");
  s = s.replace(/([^\s])が(?=[\s\u3040-\u30ff])/g, "$1 ga ");
  s = s.replace(/([^\s])を(?=[\s\u3040-\u30ff])/g, "$1 o ");
  s = s.replace(/([^\s])に(?=なる|する|入る|行く|来)/g, "$1 ni ");
  s = s.replace(/になること/g, "ni naru koto");
  s = s.replace(/すること/g, "suru koto");
  s = s.replace(/働くこと/g, "hataraku koto");
  s = s.replace(/夜遅く/g, "yoru osoku");
  s = s.replace(/遅くまで/g, "osoku made");
  s = s.replace(/([^\s])だけ(?=[\s\u3040-\u30ff])/g, "$1 dake ");
  s = s.replace(/([^\s])まで(?=[\s\u3040-\u30ff])/g, "$1 made ");
  s = s.replace(/([^\s])から(?=[\s\u3040-\u30ff])/g, "$1 kara ");
  s = s.replace(/([^\s])ので(?=[\s\u3040-\u30ff])/g, "$1 node ");
  s = s.replace(/([^\s])のに(?=[\s\u3040-\u30ff])/g, "$1 noni ");
  s = s.replace(/([^\s])より(?=[\s\u3040-\u30ff])/g, "$1 yori ");
  s = s.replace(/([^\s])こと$/g, "$1 koto");
  s = s.replace(/([^\s])もの$/g, "$1 mono");
  s = s.replace(/どういう/g, "dou iu");
  s = s.replace(/書いてあります/g, "kaite arimasu");
  s = s.replace(/ですか/g, "desu ka");
  return s;
}

/**
 * Converts any Japanese text, markup ({kanji|reading}), or TextSegment[] to clean Hepburn Romaji.
 */
export function toRomaji(input: string | TextSegment[] | undefined): string {
  if (!input) return "";

  let segs: TextSegment[] = [];
  if (Array.isArray(input)) {
    segs = enrichSegmentsWithFurigana(input);
  } else if (typeof input === "string") {
    if (/\{[^|{}]+\|[^}]+\}/.test(input)) {
      const parts = input.split(/(\{[^|{}]+\|[^}]+\})/g);
      segs = parts.map((p) => {
        if (p.startsWith("{") && p.endsWith("}") && p.includes("|")) {
          const [k, r] = p.slice(1, -1).split("|");
          return { text: k, reading: r };
        }
        return { text: p };
      });
    } else {
      segs = annotateTextWithFurigana(input);
    }
  }

  const tokens: string[] = [];
  for (let i = 0; i < segs.length; i++) {
    const s = segs[i];
    if (s.reading) {
      tokens.push(kanaToRomaji(s.reading));
    } else {
      const t = s.text || "";
      if (t === "は") {
        tokens.push("wa");
      } else if (t === "を") {
        tokens.push("o");
      } else if (t === "へ") {
        tokens.push("e");
      } else {
        const preTokenized = tokenizeKanaText(t);
        const subWords = preTokenized.split(/\s+/);
        for (const sw of subWords) {
          if (!sw) continue;
          if (
            sw === "wa" ||
            sw === "o" ||
            sw === "e" ||
            sw === "koto" ||
            sw === "dake" ||
            sw === "made" ||
            sw === "kara" ||
            sw === "node" ||
            sw === "yori"
          ) {
            tokens.push(sw);
          } else {
            tokens.push(kanaToRomaji(sw));
          }
        }
      }
    }
  }

  let res = tokens
    .join(" ")
    .replace(/\s+([、。，．,.!?！？:：」』）\)])/g, "$1")
    .replace(/([「『（\(])\s+/g, "$1")
    .replace(/([a-zA-Z0-9])([「『（\(])/g, "$1 $2")
    .replace(/([」』）\)])([a-zA-Z0-9])/g, "$1 $2")
    .replace(/\b([a-z]+)\s+(itearimasu|ite|ita|tte|tta|nde|nda)\b/g, "$1$2")
    .replace(/itearimasu/g, "ite arimasu")
    .replace(/：/g, ": ")
    .replace(/。/g, ". ")
    .replace(/、/g, ", ")
    .replace(/\s{2,}/g, " ")
    .trim();

  return res;
}

